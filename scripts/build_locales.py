#!/usr/bin/env python3
"""Validate reviewed UTF-8 catalogs and embed them without runtime HTTP dependencies."""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
LOCALES=['en','uk','es','pt-br','fr','de','it','id','ja','ko','tr','vi','th','zh-hans','zh-hant','ar','hi']
def load():
    result={}
    for locale in LOCALES:
        def unique(pairs):
            d={}
            for k,v in pairs:
                assert k not in d, f'{locale}: duplicate {k}'
                d[k]=v
            return d
        result[locale]=json.loads((ROOT/'localization'/f'{locale}.json').read_text(),object_pairs_hook=unique)
    base=result['en']
    placeholders=lambda text:set(re.findall(r'\{([a-zA-Z0-9_]+)\}',text))
    for locale,strings in result.items():
        assert strings.keys()==base.keys(),f'{locale}: missing {base.keys()-strings.keys()}, extra {strings.keys()-base.keys()}'
        for key,value in strings.items():
            assert isinstance(value,str) and value.strip(),f'{locale}:{key} empty'
            assert placeholders(value)==placeholders(base[key]),f'{locale}:{key} placeholders differ'
            assert not re.search(r'[\u202a-\u202e\u2066-\u2069]',value),f'{locale}:{key} hidden direction override'
    return result

def build():
    catalogs=load()
    q=lambda s:json.dumps(s,ensure_ascii=False)
    index=['-- Generated by scripts/build_locales.py; edit localization/*.json.','return {']
    for locale,strings in catalogs.items():
        module='Locale_'+locale.replace('-','_')
        lines=['-- Generated locale: '+locale,'return {']
        for key,value in strings.items():lines.append(' ['+q(key)+']='+q(value)+',')
        lines.append('}')
        (ROOT/'src/shared'/f'{module}.luau').write_text('\n'.join(lines)+'\n')
        index.append(' ['+q(locale)+']=require(script.Parent:WaitForChild('+q(module)+')),')
    index.append('}')
    (ROOT/'src/shared/LocaleCatalog.luau').write_text('\n'.join(index)+'\n')
    print(f'Validated {len(catalogs)} locales × {len(catalogs["en"])} keys; identical named placeholders.')
if __name__=='__main__':build()
